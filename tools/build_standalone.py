"""Build readable bot.py from the four auditable source modules.

The submitted runtime imports only Python's standard library. Older world.py or
combat.py files in a repository cannot affect its behavior.
"""
import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ('mechfight.py', 'world.py', 'combat.py', 'strategy.py')


def is_main_guard(node):
    return isinstance(node, ast.If) and isinstance(node.test, ast.Compare) and isinstance(node.test.left, ast.Name) and node.test.left.id == '__name__'


def build(root=ROOT):
    output = ['# Generated by tools/build_standalone.py; edit the source modules.',
              'from __future__ import annotations', '']
    for filename in SOURCES:
        source = (root / filename).read_text()
        tree = ast.parse(source)
        body = []
        for node in tree.body:
            if is_main_guard(node):
                continue
            if isinstance(node, ast.ImportFrom) and node.module in ('__future__', 'world', 'combat'):
                continue
            if isinstance(node, ast.Import) and any(alias.name == 'mechfight' for alias in node.names):
                body.extend(ast.parse('mf = sys.modules[__name__]').body)
                continue
            body.append(node)
        output.extend([f'# Source: {filename}; SHA-256: {hashlib.sha256(source.encode()).hexdigest()}',
                       ast.unparse(ast.Module(body=body, type_ignores=[])), ''])
    output.append("if __name__ == '__main__':\n    run(Bot)\n")
    result = '\n'.join(output)
    compile(result, str(root / 'bot.py'), 'exec')
    (root / 'bot.py').write_text(result)
    return len(result.encode())


if __name__ == '__main__':
    print('Built standalone bot.py:', build(), 'bytes')
